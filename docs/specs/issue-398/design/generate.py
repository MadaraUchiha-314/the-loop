Point = tuple[float, float]
Curve = Callable[[float], Point]
Width = Callable[[float, float], float]  # (u along the stroke, tangent angle) → width


# --------------------------------------------------------------------------- geometry


def fmt(p: Point) -> str:
    return f"{p[0]:.1f} {p[1]:.1f}"


def smoothstep(x: float) -> float:
    x = min(1.0, max(0.0, x))
    return x * x * (3 - 2 * x)


class Wobble:
    """Seeded sideways noise: a few integer harmonics of the stroke's own period. Round
    2 uses it sparingly — a hair of warmth, never a tremor."""

    def __init__(self, rng: random.Random, amp: float, harmonics=(2, 3, 5)) -> None:
        self.terms = [
            (amp / (i + 1), h, rng.uniform(0, math.tau))
            for i, h in enumerate(harmonics)
        ]

    def __call__(self, u: float) -> float:
        return sum(a * math.sin(math.tau * h * u + p) for a, h, p in self.terms)


def tangent(curve: Curve, u: float, du: float = 1e-3) -> tuple[float, float]:
    ax, ay = curve(u - du)
    bx, by = curve(u + du)
    tx, ty = bx - ax, by - ay
    norm = math.hypot(tx, ty) or 1.0
    return tx / norm, ty / norm


def trace(
    curve: Curve,
    u0: float,
    u1: float,
    n: int,
    wobble: Wobble | None = None,
) -> list[Point]:
    """Sample `curve` on [u0, u1], pushing each sample along its normal by the wobble."""
    pts: list[Point] = []
    for i in range(n + 1):
        u = u0 + (u1 - u0) * i / n
        x, y = curve(u)
        tx, ty = tangent(curve, u)
        off = wobble(u) if wobble else 0.0
        pts.append((x - ty * off, y + tx * off))
    return pts


def spline(pts: list[Point], closed: bool) -> str:
    """Catmull-Rom through the points, emitted as cubic Béziers."""
    n = len(pts)

    def at(i: int) -> Point:
        return pts[i % n] if closed else pts[min(max(i, 0), n - 1)]

    out = [f"M{fmt(pts[0])}"]
    for i in range(n if closed else n - 1):
        p0, p1, p2, p3 = at(i - 1), at(i), at(i + 1), at(i + 2)
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        out.append(f"C{fmt(c1)} {fmt(c2)} {fmt(p2)}")
    out.append("Z")
    return "".join(out)


def catmull_points(keys: list[Point], per_seg: int = 16) -> list[Point]:
    """Dense samples of the open Catmull-Rom curve through hand-placed `keys`."""
    n = len(keys)

    def at(i: int) -> Point:
        return keys[min(max(i, 0), n - 1)]

    out: list[Point] = []
    for i in range(n - 1):
        (x0, y0), (x1, y1), (x2, y2), (x3, y3) = at(i - 1), at(i), at(i + 1), at(i + 2)
        for k in range(per_seg):
            t = k / per_seg
            t2, t3 = t * t, t * t * t
            x = 0.5 * (
                2 * x1
                + (-x0 + x2) * t
                + (2 * x0 - 5 * x1 + 4 * x2 - x3) * t2
                + (-x0 + 3 * x1 - 3 * x2 + x3) * t3
            )
            y = 0.5 * (
                2 * y1
                + (-y0 + y2) * t
                + (2 * y0 - 5 * y1 + 4 * y2 - y3) * t2
                + (-y0 + 3 * y1 - 3 * y2 + y3) * t3
            )
            out.append((x, y))
    out.append(keys[-1])
    return out


def by_arc_length(points: list[Point]) -> tuple[Curve, float]:
    """A curve through dense `points`, parameterised by arc length on [0, 1], so the
    brush's pressure and lifts are even along the stroke. Returns (curve, length)."""
    lengths = [0.0]
    for (x0, y0), (x1, y1) in zip(points, points[1:], strict=False):
        lengths.append(lengths[-1] + math.hypot(x1 - x0, y1 - y0))
    total = lengths[-1] or 1.0

    def f(u: float) -> Point:
        s = min(max(u, 0.0), 1.0) * total
        i = min(max(bisect.bisect_right(lengths, s) - 1, 0), len(points) - 2)
        seg = lengths[i + 1] - lengths[i] or 1.0
        t = (s - lengths[i]) / seg
        (x0, y0), (x1, y1) = points[i], points[i + 1]
        return (x0 + (x1 - x0) * t, y0 + (y1 - y0) * t)

    return f, total


def circumradius(a: Point, b: Point, c: Point) -> float:
    """Radius of the circle through three points (huge when they are collinear)."""
    ab = math.hypot(b[0] - a[0], b[1] - a[1])
    bc = math.hypot(c[0] - b[0], c[1] - b[1])
    ca = math.hypot(a[0] - c[0], a[1] - c[1])
    area2 = abs((b[0] - a[0]) * (c[1] - a[1]) - (c[0] - a[0]) * (b[1] - a[1]))
    return (ab * bc * ca) / (2 * area2) if area2 > 1e-9 else 1e9


def outline(
    pts: list[Point], width: Width, closed: bool, u0: float = 0.0, u1: float = 1.0
) -> str:
    """The filled outline of a variable-width stroke along `pts`. The width function
    sees the stroke's global parameter (u0..u1) and the tangent angle at each sample."""
    if closed:
        pts = pts[:-1]
    n = len(pts)
    left: list[Point] = []
    right: list[Point] = []
    for i, (x, y) in enumerate(pts):
        if closed:
            (ax, ay), (bx, by) = pts[(i - 1) % n], pts[(i + 1) % n]
        else:
            (ax, ay), (bx, by) = pts[max(i - 1, 0)], pts[min(i + 1, n - 1)]
        tx, ty = bx - ax, by - ay
        norm = math.hypot(tx, ty) or 1.0
        nx, ny = -ty / norm, tx / norm
        u = u0 + (u1 - u0) * i / (n - 1)
        w = width(u, math.atan2(ty, tx)) / 2
        # never offset past the centre of curvature: the offset curve would fold back on
        # itself and punch a hole where a pen would simply pool
        w = min(w, 0.85 * circumradius((ax, ay), (x, y), (bx, by)))
        left.append((x + nx * w, y + ny * w))
        right.append((x - nx * w, y - ny * w))
    if closed:
        return spline(left, True) + spline(right[::-1], True)
    return spline(left + right[::-1], True)


def brush(
    base: float,
    *,
    nib_deg: float = 32.0,
    contrast: float = 0.55,
    entry: float = 0.06,
    exit: float = 0.10,
    swell: float = 0.0,
    swell_at: float = 0.5,
    floor: float = 0.10,
) -> Width:
    """A flat brush held at `nib_deg`: full width across the nib, `1 - contrast` of it
    along the nib; pressed harder around `swell_at`; lifted in over `entry` and out over
    `exit` of the stroke (a lift of 0 keeps the end blunt)."""
    nib = math.radians(nib_deg)

    def width(u: float, ang: float) -> float:
        angular = 1 - contrast * (1 - abs(math.sin(ang - nib)))
        pressure = 1 + swell * math.exp(-((u - swell_at) ** 2) / 0.08)
        lift = 1.0
        if entry:
            lift *= floor + (1 - floor) * smoothstep(u / entry)
        if exit:
            lift *= floor + (1 - floor) * smoothstep((1 - u) / exit)
        return max(base * angular * pressure * lift, 0.5)

    return width


def enso_brush(base: float, *, nib_deg: float = 15.0, contrast: float = 0.2) -> Width:
    """The one-breath circle: down heavy at the start, thinning to a dry tail."""
    nib = math.radians(nib_deg)

    def width(u: float, ang: float) -> float:
        angular = 1 - contrast * (1 - abs(math.sin(ang - nib)))
        body = 1.0 + 0.12 * smoothstep(u / 0.2) - 0.92 * smoothstep((u - 0.45) / 0.55)
        start = 0.6 + 0.4 * smoothstep(u / 0.04)
        return max(base * angular * body * start, 0.6)

    return width


# ----------------------------------------------------------------------------- curves


def ellipse(cx: float, cy: float, rx: float, ry: float, rot_deg: float = 0.0) -> Curve:
    r = math.radians(rot_deg)
    cr, sr = math.cos(r), math.sin(r)

    def f(u: float) -> Point:
        t = math.tau * u
        x, y = rx * math.cos(t), ry * math.sin(t)
        return (cx + x * cr - y * sr, cy + x * sr + y * cr)

    return f


def circle(cx: float, cy: float, r: float) -> Curve:
    return ellipse(cx, cy, r, r)


def arc(
    cx: float, cy: float, r: float, a0: float, a1: float, n: int = 24
) -> list[Point]:
    """Points along a circular arc from angle a0 to a1 (degrees, SVG orientation)."""
    return [
        (
            cx + r * math.cos(math.radians(a0 + (a1 - a0) * i / n)),
            cy + r * math.sin(math.radians(a0 + (a1 - a0) * i / n)),
        )
        for i in range(n + 1)
    ]


def placed(
    points: list[Point],
    *,
    scale: float,
    rot_deg: float,
    cx: float = C,
    cy: float = C,
    flip_y: bool = False,
) -> list[Point]:
    """Scale, rotate and centre a point list on the canvas (flip_y for y-up drawings)."""
    xs = [p[0] for p in points]
    ys = [p[1] for p in points]
    mx, my = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
    r = math.radians(rot_deg)
    cr, sr = math.cos(r), math.sin(r)
    out = []
    for x, y in points:
        x, y = (x - mx) * scale, (y - my) * scale * (-1 if flip_y else 1)
        out.append((cx + x * cr - y * sr, cy + x * sr + y * cr))
    return out


def trefoil(scale: float, rot_deg: float) -> Curve:
    """The simplest knot: one line, three lobes, six alternating crossings."""
    r = math.radians(rot_deg)
    cr, sr = math.cos(r), math.sin(r)

    def f(u: float) -> Point:
        t = math.tau * u
        x = (math.sin(t) + 2 * math.sin(2 * t)) * scale
        y = (math.cos(t) - 2 * math.cos(2 * t)) * scale
        return (C + x * cr - y * sr, C + x * sr + y * cr)

    return f


# ---------------------------------------------------------------------------- strokes


@dataclass
class Shape:
    """One filled SVG path (plus, for a woven stroke, the mask that carves the gaps)."""

    d: str
    fill: str
    opacity: float = 1.0
    mask: str = ""  # id of a mask this path is drawn through
    defs: list[str] = field(default_factory=list)  # <mask> elements this shape needs

    def svg(self) -> str:
        fill = "currentColor" if self.fill == INK else self.fill
        attrs = [f'd="{self.d}"', f'fill="{fill}"']
        if self.opacity < 1:
            attrs.append(f'opacity="{self.opacity:.2f}"')
        if self.mask:
            attrs.append(f'mask="url(#{self.mask})"')
        return "".join(self.defs) + f"<path {' '.join(attrs)}/>"


def stroke(
    curve: Curve,
    width: Width,
    *,
    fill: str,
    u0: float = 0.0,
    u1: float = 1.0,
    samples: int = 160,
    wobble: Wobble | None = None,
    closed: bool = False,
) -> Shape:
    pts = trace(curve, u0, u1, samples, wobble)
    # the brush sees progress along the drawn stroke, not the curve's own parameter
    return Shape(outline(pts, width, closed), fill)


def crossings(curve: Curve, samples: int = 480) -> list[tuple[float, float]]:
    """Parameter pairs (u_a, u_b) where the curve crosses itself."""
    pts = [curve(i / samples) for i in range(samples + 1)]
    found: list[tuple[float, float]] = []
    for i in range(samples):
        (ax, ay), (bx, by) = pts[i], pts[i + 1]
        for j in range(i + 2, samples):
            if i == 0 and j == samples - 1:
                continue  # the closing segment is adjacent to the first
            (cx, cy), (dx, dy) = pts[j], pts[j + 1]
            den = (bx - ax) * (dy - cy) - (by - ay) * (dx - cx)
            if abs(den) < 1e-12:
                continue
            s = ((cx - ax) * (dy - cy) - (cy - ay) * (dx - cx)) / den
            t = ((cx - ax) * (by - ay) - (cy - ay) * (bx - ax)) / den
            if 0 <= s < 1 and 0 <= t < 1:
                found.append(((i + s) / samples, (j + t) / samples))
    return found


def woven(
    curve: Curve,
    width: Width,
    *,
    fill: str,
    mask_id: str,
    base_width: float,
    samples: int = 480,
    gap: float | None = None,
    reach: float | None = None,
) -> Shape:
    """A closed stroke that crosses itself, drawn as rope: at each crossing the strand
    visited later in an alternating walk passes *over* — the under strand is carved
    away around it by a mask, so the weave holds on any background."""
    gap = gap if gap is not None else base_width * 0.42
    reach = reach if reach is not None else base_width * 2.1
    # arc length, to turn a reach in pixels into a span in u
    pts = [curve(i / samples) for i in range(samples + 1)]
    total = sum(
        math.hypot(b[0] - a[0], b[1] - a[1]) for a, b in zip(pts, pts[1:], strict=False)
    )
    span = reach / total
    visits = sorted(
        (u, k) for k, pair in enumerate(crossings(curve, samples)) for u in pair
    )
    over = [u for n, (u, _k) in enumerate(visits) if n % 2 == 0]
    halos: list[str] = []
    tops: list[str] = []
    for u in over:
        seg = trace(curve, u - span, u + span, 40)
        halos.append(
            outline(
                seg, lambda uu, ang: width(uu, ang) + 2 * gap, False, u - span, u + span
            )
        )
        tops.append(outline(seg, width, False, u - span, u + span))
    body = outline(trace(curve, 0.0, 1.0, samples), width, True)
    mask = (
        f'<mask id="{mask_id}" maskUnits="userSpaceOnUse" x="0" y="0" width="{SIZE:.0f}" height="{SIZE:.0f}">'
        f'<rect width="{SIZE:.0f}" height="{SIZE:.0f}" fill="#fff"/>'
        + "".join(f'<path d="{h}" fill="#000"/>' for h in halos)
        + "</mask>"
    )
    return Shape(body + "".join(tops), fill, mask=mask_id, defs=[mask])


def arrowhead(
    curve: Curve, *, fill: str, length: float = 22.0, half: float = 11.0, u: float = 1.0
) -> Shape:
    """A filled chevron whose tip continues the stroke's direction at `u`."""
    px, py = curve(u)
    tx, ty = tangent(curve, u)
    nx, ny = -ty, tx
    tip = (px + tx * length, py + ty * length)
    left = (px - tx * length * 0.3 + nx * half, py - ty * length * 0.3 + ny * half)
    right = (px - tx * length * 0.3 - nx * half, py - ty * length * 0.3 - ny * half)
    return Shape(f"M{fmt(left)}L{fmt(tip)}L{fmt(right)}Z", fill)


