# ------------------------------------------------------------------------------- svg


def svg_body(opt: Option) -> str:
    return "\n".join(s.svg() for s in opt.shapes)


def svg_file(opt: Option) -> str:
    """The standalone file. The ink is `currentColor`, set once on the root and swapped
    for the dark-scheme ink by the one media rule; accents are mid-toned enough for
    either ground."""
    title = f"the-loop — {opt.name}"
    style = f"@media (prefers-color-scheme:dark){{svg{{color:{INK_ON_SLATE}}}}}"
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {SIZE:.0f} {SIZE:.0f}" '
        f'color="{INK}" role="img" aria-labelledby="{opt.slug}-title {opt.slug}-desc">\n'
        f'<title id="{opt.slug}-title">{title}</title>\n'
        f'<desc id="{opt.slug}-desc">{opt.concept} Generated by docs/specs/issue-398/design/generate.py.</desc>\n'
        f"<style>{style}</style>\n"
        f"{svg_body(opt)}\n"
        "</svg>\n"
    )


def svg_symbol(opt: Option) -> str:
    return f'<symbol id="{opt.slug}" viewBox="0 0 {SIZE:.0f} {SIZE:.0f}">{svg_body(opt)}</symbol>'


def svg_use(opt: Option, px: int) -> str:
    return f'<svg width="{px}" height="{px}" aria-hidden="true"><use href="#{opt.slug}"/></svg>'


