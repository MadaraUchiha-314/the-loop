# ------------------------------------------------------------------------------- svg


def svg_body(v: Variant) -> str:
    return "\n".join(s.svg() for s in render_variant(v))


def dark_rules(v: Variant) -> str:
    """Per-piece dark-scheme fills for a travelling ring that starts or ends in ink."""
    return "".join(f".{s.cls}{{fill:{s.dark}}}" for s in render_variant(v) if s.dark)


def svg_file(v: Variant) -> str:
    """The standalone file. Flat ink is `currentColor`, set once on the root and swapped
    for the dark-scheme ink by the one media rule; accents are mid-toned enough for
    either ground; a travelling ring that touches ink carries its own dark fills."""
    title = f"the-loop — Ensō, {v.name}"
    dark = f"svg{{color:{INK_ON_SLATE}}}{dark_rules(v)}"
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {SIZE:.0f} {SIZE:.0f}" '
        f'color="{INK}" role="img" aria-labelledby="{v.slug}-title {v.slug}-desc">\n'
        f'<title id="{v.slug}-title">{title}</title>\n'
        f'<desc id="{v.slug}-desc">Three brush circles, each left open where the hand lifted; {v.note}. Generated by docs/specs/issue-398/design/generate.py.</desc>\n'
        f"<style>@media (prefers-color-scheme:dark){{{dark}}}</style>\n"
        f"{svg_body(v)}\n"
        "</svg>\n"
    )


def svg_symbol(v: Variant) -> str:
    return f'<symbol id="{v.slug}" viewBox="0 0 {SIZE:.0f} {SIZE:.0f}">{svg_body(v)}</symbol>'


def svg_use(v: Variant, px: int) -> str:
    return f'<svg width="{px}" height="{px}" aria-hidden="true"><use href="#{v.slug}"/></svg>'


