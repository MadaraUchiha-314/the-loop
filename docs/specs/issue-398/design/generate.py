    shapes = []
    for r, fill, start, base in (
        (100, INK, 118, 16.0),
        (65, DUSK, 250, 13.0),
        (33, CLAY, 20, 9.5),
    ):
        u0 = start / 360
        shapes.append(
            stroke(
                circle(C, C, r),
                enso_brush(base),
                fill=fill,
                u0=u0,
                u1=u0 + 0.875,
                samples=200,
                wobble=Wobble(rng, 0.6),
            )
        )
    return Option(
        "option-5-enso",
        "Ensō",
        "calm",
        "Three brush circles, each left open where the hand lifted: the outer loop, the inner loop, and the one between — none of them closed until the work is.",
        [
            "One breath per circle, heavy where it starts and dry where it ends; the gap is the loop still running.",
            "Nested, not concentric in spirit: each opens at its own angle, each is its own colour.",
            "The quiet option — a mark that reads at any size and asks nothing of the eye.",
        ],
        "three arcs of 315°, each a brush that starts heavy and thins to a dry tail; ink, dusk and clay",
        shapes,
    )


