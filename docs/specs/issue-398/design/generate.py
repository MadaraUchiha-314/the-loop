# ------------------------------------------------------------------------------- svg


def svg_body(opt: Option, blend: str | None = None) -> str:
    return "\n".join(r.svg(blend) for r in opt.ribbons)


def svg_file(opt: Option) -> str:
    """The standalone file. The ink is `currentColor`, set once on the root and swapped
    for the dark-scheme ink by the one media rule; accents are mid-toned enough for
    either ground. A blended option carries its two blend modes the same way."""
    title = f"the-loop — {opt.name}"
    dark = f"svg{{color:{INK_ON_SLATE}}}" + (
        ".blend{mix-blend-mode:screen}" if opt.style else ""
    )
    style = f"{opt.style}@media (prefers-color-scheme:dark){{{dark}}}"
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {SIZE:.0f} {SIZE:.0f}" '
        f'color="{INK}" role="img" aria-labelledby="{opt.slug}-title {opt.slug}-desc">\n'
        f'<title id="{opt.slug}-title">{title}</title>\n'
        f'<desc id="{opt.slug}-desc">{opt.concept} Generated by docs/specs/issue-398/design/generate.py.</desc>\n'
        f"<style>{style}</style>\n"
        f"{svg_body(opt)}\n"
        "</svg>\n"
    )


def symbol_id(opt: Option, ground: str) -> str:
    return f"{opt.slug}-{ground}" if opt.style else opt.slug


def svg_symbols(opt: Option) -> str:
    """One <symbol> per option for the gallery to <use>; a blended option gets one per
    ground, since a mix-blend-mode cannot follow the <use> element's context."""
    if not opt.style:
        return f'<symbol id="{opt.slug}" viewBox="0 0 {SIZE:.0f} {SIZE:.0f}">{svg_body(opt)}</symbol>'
    return "".join(
        f'<symbol id="{symbol_id(opt, ground)}" viewBox="0 0 {SIZE:.0f} {SIZE:.0f}">{svg_body(opt, mode)}</symbol>'
        for ground, mode in (("paper", "multiply"), ("slate", "screen"))
    )


def svg_use(opt: Option, px: int, ground: str = "paper") -> str:
    return f'<svg width="{px}" height="{px}" aria-hidden="true"><use href="#{symbol_id(opt, ground)}"/></svg>'


