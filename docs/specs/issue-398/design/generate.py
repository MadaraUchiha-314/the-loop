def ring_swatches(v: Variant) -> str:
    def css(paint: Paint) -> str:
        if v.sweep:
            return f"linear-gradient(135deg,{v.sweep[0]},{v.sweep[1]})"
        if isinstance(paint, tuple):
            c0 = INK if paint[0] == "ink" else paint[0]
            c1 = INK if paint[1] == "ink" else paint[1]
            return f"linear-gradient(90deg,{c0},{c1})"
        return INK if paint == "ink" else paint

    return (
        '<span class="rings">'
        + "".join(f'<i style="background:{css(p)}"></i>' for p in v.rings)
        + "</span>"
    )


