        '<desc id="the-loop-logo-desc">the-loop\'s mark: three brush circles, each left open where the hand lifted — the outer loop, the inner loop, and the one between; '
        f"{v.name}. Generated by docs/specs/issue-398/design/generate.py.</desc>\n"
