@dataclass
class Shape:
    """One filled SVG path, with any <defs> it needs and a dark-scheme fill if its
    light one is not legible on slate."""

    d: str
    fill: str
    cls: str = ""
    dark: str = ""
    defs: list[str] = field(default_factory=list)

    def svg(self) -> str:
        attrs = [f'd="{self.d}"', f'fill="{self.fill}"']
        if self.cls:
            attrs.insert(0, f'class="{self.cls}"')
        return "".join(self.defs) + f"<path {' '.join(attrs)}/>"


# radius, angle the brush lands at, base width — the round-2 Ensō, unchanged
RINGS = ((100.0, 118.0, 16.0), (65.0, 250.0, 13.0), (33.0, 20.0, 9.5))
ARC = 0.875  # 315° of each circle; the gap is where the hand lifted
CHUNKS = 20  # pieces per stroke when the colour travels along it
SEED = 398_5

Paint = (
    str | tuple[str, str]
)  # a flat colour ("ink" allowed), or (start, end) along the stroke


@dataclass
class Variant:
    slug: str
    name: str
    note: str
    rings: tuple[Paint, Paint, Paint]  # outer, middle, inner
    sweep: tuple[str, str] | None = None  # one linear gradient across the whole mark

    @property
    def gradient(self) -> bool:
        return self.sweep is not None or any(isinstance(p, tuple) for p in self.rings)


def ring_curves() -> list[tuple[Curve, Wobble, float, float]]:
    """The three strokes' geometry, identical for every colourway."""
    rng = random.Random(SEED)
    out = []
    for r, start, base in RINGS:
        out.append((circle(C, C, r), Wobble(rng, 0.6), start / 360, base))
    return out


SAMPLES = 200  # per stroke


def flat_ring(curve: Curve, wobble: Wobble, u0: float, base: float, fill: str) -> Shape:
    pts = trace(curve, u0, u0 + ARC, SAMPLES, wobble)
    return Shape(outline(pts, enso_brush(base)), fill)


def travelling_ring(
    curve: Curve,
    wobble: Wobble,
    u0: float,
    base: float,
    c0: str,
    c1: str,
    ring: int,
    slug: str,
) -> list[Shape]:
    """The stroke in CHUNKS pieces, each a shade further from c0 toward c1 — the colour
    travels with the brush. The pieces are cut from ONE outline, so their edges abut
    exactly; each overlaps the next by a sample to hide the seam. A piece whose light
    colour starts from the ink gets a dark-scheme colour too, from the slate ink,
    through a class the stylesheet maps."""
    left, right = edges(trace(curve, u0, u0 + ARC, SAMPLES, wobble), enso_brush(base))
    shapes: list[Shape] = []
    per = SAMPLES // CHUNKS
    for k in range(CHUNKS):
        i0 = k * per
        i1 = SAMPLES if k == CHUNKS - 1 else (k + 1) * per + 1  # +1: overlap the seam
        d = piece(left, right, i0, i1)
        t = (k + 0.5) / CHUNKS
        light = mix(INK if c0 == "ink" else c0, INK if c1 == "ink" else c1, t)
        dark = ""
        if "ink" in (c0, c1):
            dark = mix(
                INK_ON_SLATE if c0 == "ink" else c0,
                INK_ON_SLATE if c1 == "ink" else c1,
                t,
            )
        shapes.append(
            Shape(d, light, cls=f"{slug}-r{ring}-{k}" if dark else "", dark=dark)
        )
    return shapes


def render_variant(v: Variant) -> list[Shape]:
    shapes: list[Shape] = []
    if v.sweep:
        gid = f"{v.slug}-sweep"
        defs = (
            f'<linearGradient id="{gid}" gradientUnits="userSpaceOnUse" x1="36" y1="36" x2="220" y2="220">'
            f'<stop offset="0" stop-color="{v.sweep[0]}"/><stop offset="1" stop-color="{v.sweep[1]}"/></linearGradient>'
        )
        for i, (curve, wobble, u0, base) in enumerate(ring_curves()):
            s = flat_ring(curve, wobble, u0, base, f"url(#{gid})")
            if i == 0:
                s.defs.append(defs)
            shapes.append(s)
        return shapes
    for i, ((curve, wobble, u0, base), paint) in enumerate(
        zip(ring_curves(), v.rings, strict=True)
    ):
        if isinstance(paint, tuple):
            shapes += travelling_ring(
                curve, wobble, u0, base, paint[0], paint[1], i, v.slug
            )
        else:
            shapes.append(
                flat_ring(
                    curve, wobble, u0, base, "currentColor" if paint == "ink" else paint
                )
            )
    return shapes


