# --------------------------------------------------------------------------- geometry


def fmt(p: Point) -> str:
    return f"{p[0]:.1f} {p[1]:.1f}"


def smoothstep(x: float) -> float:
    x = min(1.0, max(0.0, x))
    return x * x * (3 - 2 * x)


class Wobble:
    """Seeded sideways noise: a few integer harmonics of the stroke's own period — a
    hair of warmth, never a tremor."""

    def __init__(self, rng: random.Random, amp: float, harmonics=(2, 3, 5)) -> None:
        self.terms = [
            (amp / (i + 1), h, rng.uniform(0, math.tau))
            for i, h in enumerate(harmonics)
        ]

    def __call__(self, u: float) -> float:
        return sum(a * math.sin(math.tau * h * u + p) for a, h, p in self.terms)


def tangent(curve: Curve, u: float, du: float = 1e-3) -> tuple[float, float]:
    ax, ay = curve(u - du)
    bx, by = curve(u + du)
    tx, ty = bx - ax, by - ay
    norm = math.hypot(tx, ty) or 1.0
    return tx / norm, ty / norm


def trace(
    curve: Curve, u0: float, u1: float, n: int, wobble: Wobble | None = None
) -> list[Point]:
    """Sample `curve` on [u0, u1], pushing each sample along its normal by the wobble."""
    pts: list[Point] = []
    for i in range(n + 1):
        u = u0 + (u1 - u0) * i / n
        x, y = curve(u)
        tx, ty = tangent(curve, u)
        off = wobble(u) if wobble else 0.0
        pts.append((x - ty * off, y + tx * off))
    return pts


def spline(pts: list[Point], closed: bool) -> str:
    """Catmull-Rom through the points, emitted as cubic Béziers."""
    n = len(pts)

    def at(i: int) -> Point:
        return pts[i % n] if closed else pts[min(max(i, 0), n - 1)]

    out = [f"M{fmt(pts[0])}"]
    for i in range(n if closed else n - 1):
        p0, p1, p2, p3 = at(i - 1), at(i), at(i + 1), at(i + 2)
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        out.append(f"C{fmt(c1)} {fmt(c2)} {fmt(p2)}")
    out.append("Z")
    return "".join(out)


def circumradius(a: Point, b: Point, c: Point) -> float:
    """Radius of the circle through three points (huge when they are collinear)."""
    ab = math.hypot(b[0] - a[0], b[1] - a[1])
    bc = math.hypot(c[0] - b[0], c[1] - b[1])
    ca = math.hypot(a[0] - c[0], a[1] - c[1])
    area2 = abs((b[0] - a[0]) * (c[1] - a[1]) - (c[0] - a[0]) * (b[1] - a[1]))
    return (ab * bc * ca) / (2 * area2) if area2 > 1e-9 else 1e9


def edges(pts: list[Point], width: Width) -> tuple[list[Point], list[Point]]:
    """The left and right edges of a variable-width open stroke along `pts`. The width
    function sees the stroke's progress (0..1) and the tangent angle at each sample."""
    n = len(pts)
    left: list[Point] = []
    right: list[Point] = []
    for i, (x, y) in enumerate(pts):
        (ax, ay), (bx, by) = pts[max(i - 1, 0)], pts[min(i + 1, n - 1)]
        tx, ty = bx - ax, by - ay
        norm = math.hypot(tx, ty) or 1.0
        nx, ny = -ty / norm, tx / norm
        w = width(i / (n - 1), math.atan2(ty, tx)) / 2
        # never offset past the centre of curvature: the offset curve would fold back on
        # itself and punch a hole where a pen would simply pool
        w = min(w, 0.85 * circumradius((ax, ay), (x, y), (bx, by)))
        left.append((x + nx * w, y + ny * w))
        right.append((x - nx * w, y - ny * w))
    return left, right


def outline(pts: list[Point], width: Width) -> str:
    """The filled outline of a whole stroke."""
    left, right = edges(pts, width)
    return spline(left + right[::-1], True)


def segment(pts: list[Point], i0: float, i1: float) -> str:
    """The cubic Béziers of the open Catmull-Rom curve through `pts` from index i0 to
    i1 — the same segments `spline` would emit for the whole list, so a piece cut
    here abuts its neighbour on an identical curve."""
    n = len(pts)

    def at(i: int) -> Point:
        return pts[min(max(i, 0), n - 1)]

    out = []
    for i in range(int(i0), int(i1)):
        p0, p1, p2, p3 = at(i - 1), at(i), at(i + 1), at(i + 2)
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        out.append(f"C{fmt(c1)} {fmt(c2)} {fmt(p2)}")
    return "".join(out)


def piece(left: list[Point], right: list[Point], i0: int, i1: int) -> str:
    """One piece of a stroke: along the left edge from i0 to i1 on the stroke's own
    curve, straight across, back along the right edge, straight across again."""
    n = len(left)
    rev = right[::-1]
    return (
        f"M{fmt(left[i0])}"
        + segment(left, i0, i1)
        + f"L{fmt(right[i1])}"
        + segment(rev, n - 1 - i1, n - 1 - i0)
        + "Z"
    )


def enso_brush(base: float, *, nib_deg: float = 15.0, contrast: float = 0.2) -> Width:
    """The one-breath circle: down heavy at the start, thinning to a dry tail."""
    nib = math.radians(nib_deg)

    def width(u: float, ang: float) -> float:
        angular = 1 - contrast * (1 - abs(math.sin(ang - nib)))
        body = 1.0 + 0.12 * smoothstep(u / 0.2) - 0.92 * smoothstep((u - 0.45) / 0.55)
        start = 0.6 + 0.4 * smoothstep(u / 0.04)
        return max(base * angular * body * start, 0.6)

    return width


def circle(cx: float, cy: float, r: float) -> Curve:
    def f(u: float) -> Point:
        t = math.tau * u
        return (cx + r * math.cos(t), cy + r * math.sin(t))

    return f


# ------------------------------------------------------------------------------ colour


def _srgb_to_linear(c: float) -> float:
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def _linear_to_srgb(c: float) -> float:
    c = min(1.0, max(0.0, c))
    return 12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055


def to_oklab(hexv: str) -> tuple[float, float, float]:
    r, g, b = (_srgb_to_linear(int(hexv[i : i + 2], 16) / 255) for i in (1, 3, 5))
    l_ = (0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b) ** (1 / 3)
    m_ = (0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b) ** (1 / 3)
    s_ = (0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b) ** (1 / 3)
    return (
        0.2104542553 * l_ + 0.7936177850 * m_ - 0.0040720468 * s_,
        1.9779984951 * l_ - 2.4285922050 * m_ + 0.4505937099 * s_,
        0.0259040371 * l_ + 0.7827717662 * m_ - 0.8086757660 * s_,
    )


def from_oklab(lab: tuple[float, float, float]) -> str:
    ll, a, b = lab
    l_ = (ll + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m_ = (ll - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s_ = (ll - 0.0894841775 * a - 1.2914855480 * b) ** 3
    r = 4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_
    g = -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_
    bb = -0.0041960863 * l_ - 0.7034186147 * m_ + 1.7076147010 * s_
    return "#" + "".join(f"{round(_linear_to_srgb(c) * 255):02x}" for c in (r, g, bb))


def mix(c0: str, c1: str, t: float) -> str:
    """Perceptual (OKLab) blend of two colours; t=0 is c0, t=1 is c1."""
    a, b = to_oklab(c0), to_oklab(c1)
    return from_oklab(tuple(a[i] + (b[i] - a[i]) * t for i in range(3)))  # type: ignore[arg-type]


