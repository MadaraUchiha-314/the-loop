def render() -> dict[str, str]:
    options = [make() for make in OPTIONS]
    files = {f"{opt.slug}.svg": svg_file(opt) for opt in options}
    files["logo-options.html"] = gallery(options)
    return files


FORBIDDEN = ("<script", "<foreignObject", "<image", "<iframe", "@import", "src=")
EXTERNAL_REF = re.compile(
    r'href="(?!#)|url\((?!#)'
)  # a fragment is the file's own <use> or <mask>


def check(files: dict[str, str]) -> list[str]:
    problems: list[str] = []
    for name, content in files.items():
        path = HERE / name
        if not path.exists():
            problems.append(f"{name}: missing")
            continue
        if path.read_text(encoding="utf-8") != content:
            problems.append(
                f"{name}: differs from what generate.py produces (re-run it)"
            )
        if name.endswith(".svg"):
            try:
                root = ET.fromstring(content)
            except ET.ParseError as e:
                problems.append(f"{name}: not well-formed XML ({e})")
                continue
            ns = "{http://www.w3.org/2000/svg}"
            if root.find(f"{ns}title") is None or root.find(f"{ns}desc") is None:
                problems.append(f"{name}: missing <title> or <desc>")
            if len(content.encode()) > 64_000:
                problems.append(f"{name}: over 64 kB")
        for token in FORBIDDEN:
            if token in content:
                problems.append(f"{name}: contains {token!r}")
        if EXTERNAL_REF.search(content):
            problems.append(f"{name}: has an href or url() that is not a fragment")
    if render() != files:
        problems.append("generate.py is not deterministic")
    return problems


def main(argv: list[str]) -> int:
    files = render()
    if "--check" in argv:
        problems = check(files)
        for p in problems:
            print(f"FAIL {p}")
        if not problems:
            print(f"ok — {len(files)} files match, well-formed, self-contained, titled")
        return 1 if problems else 0
    for name, content in files.items():
        (HERE / name).write_text(content, encoding="utf-8")
        print(f"wrote {name} ({len(content.encode()) / 1000:.1f} kB)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
