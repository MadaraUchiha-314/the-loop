Width = Callable[[float], float]


# --------------------------------------------------------------------------- geometry


def fmt(p: Point) -> str:
    return f"{p[0]:.1f} {p[1]:.1f}"


def smoothstep(x: float) -> float:
    x = min(1.0, max(0.0, x))
    return x * x * (3 - 2 * x)


class Wobble:
    """Seeded sideways noise: a few integer harmonics of the loop's own period, so a
    closed loop's wobble is seamless where it meets itself."""

    def __init__(self, rng: random.Random, amp: float, harmonics=(2, 3, 5)) -> None:
        self.terms = [
            (amp / (i + 1), h, rng.uniform(0, math.tau))
            for i, h in enumerate(harmonics)
        ]

    def __call__(self, u: float) -> float:
        return sum(a * math.sin(math.tau * h * u + p) for a, h, p in self.terms)


def trace(
    curve: Curve,
    u0: float,
    u1: float,
    n: int,
    wobble: Wobble | None = None,
    drift: float = 0.0,
) -> list[Point]:
    """Sample `curve` on [u0, u1], pushing each sample along its normal by the wobble.
    `drift` eases the last stretch of an overshooting loop outward, so the closing
    stroke lands beside the opening one instead of exactly on it."""
    pts: list[Point] = []
    for i in range(n + 1):
        u = u0 + (u1 - u0) * i / n
        x, y = curve(u)
        ax, ay = curve(u - 1e-3)
        bx, by = curve(u + 1e-3)
        tx, ty = bx - ax, by - ay
        norm = math.hypot(tx, ty) or 1.0
        nx, ny = -ty / norm, tx / norm
        off = wobble(u) if wobble else 0.0
        if drift:
            off += drift * smoothstep((u - u0 - 0.82) / (u1 - u0 - 0.82))
        pts.append((x + nx * off, y + ny * off))
    return pts


def spline(pts: list[Point], closed: bool) -> str:
    """Catmull-Rom through the points, emitted as cubic Béziers."""
    n = len(pts)

    def at(i: int) -> Point:
        return pts[i % n] if closed else pts[min(max(i, 0), n - 1)]

    out = [f"M{fmt(pts[0])}"]
    for i in range(n if closed else n - 1):
        p0, p1, p2, p3 = at(i - 1), at(i), at(i + 1), at(i + 2)
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        out.append(f"C{fmt(c1)} {fmt(c2)} {fmt(p2)}")
    out.append("Z")
    return "".join(out)


def outline(pts: list[Point], width: Width, closed: bool) -> str:
    """The filled outline of a variable-width ribbon along `pts`."""
    if closed:
        pts = pts[:-1]
    n = len(pts)
    left: list[Point] = []
    right: list[Point] = []
    for i, (x, y) in enumerate(pts):
        if closed:
            (ax, ay), (bx, by) = pts[(i - 1) % n], pts[(i + 1) % n]
        else:
            (ax, ay), (bx, by) = pts[max(i - 1, 0)], pts[min(i + 1, n - 1)]
        tx, ty = bx - ax, by - ay
        norm = math.hypot(tx, ty) or 1.0
        nx, ny = -ty / norm, tx / norm
        w = width(i / (n - 1)) / 2
        left.append((x + nx * w, y + ny * w))
        right.append((x - nx * w, y - ny * w))
    if closed:
        return spline(left, True) + spline(right[::-1], True)
    return spline(left + right[::-1], True)


def pen(
    rng: random.Random, base: float, swell: float = 0.3, taper: float = 0.0
) -> Width:
    """A pen whose pressure swells once around the loop and tapers at the ends."""
    p1, p2 = rng.uniform(0, math.tau), rng.uniform(0, math.tau)

    def width(u: float) -> float:
        w = base * (
            1
            + swell * math.sin(math.tau * u + p1)
            + 0.12 * math.sin(3 * math.tau * u + p2)
        )
        if taper:
            w *= 0.15 + 0.85 * smoothstep(min(u, 1 - u) / taper)
        return max(w, 0.5)

    return width


# ----------------------------------------------------------------------------- curves


def ellipse(cx: float, cy: float, rx: float, ry: float, rot_deg: float = 0.0) -> Curve:
    r = math.radians(rot_deg)
    cr, sr = math.cos(r), math.sin(r)

    def f(u: float) -> Point:
        t = math.tau * u
        x, y = rx * math.cos(t), ry * math.sin(t)
        return (cx + x * cr - y * sr, cy + x * sr + y * cr)

    return f


def circle(cx: float, cy: float, r: float) -> Curve:
    return ellipse(cx, cy, r, r)


def epitrochoid(
    cx: float,
    cy: float,
    big: float,
    small: float,
    d: float,
    scale: float,
    rot_deg: float = 0.0,
) -> Curve:
    """A point at distance `d` from the centre of a circle of radius `small` rolling
    around the outside of a circle of radius `big`. With d > small the point loops
    back on itself once per revolution of the small circle — big/small loops, all
    pointing inward, drawn in one continuous line."""
    k = (big + small) / small
    r = math.radians(rot_deg)
    cr, sr = math.cos(r), math.sin(r)

    def f(u: float) -> Point:
        t = math.tau * u
        x = ((big + small) * math.cos(t) - d * math.cos(k * t)) * scale
        y = ((big + small) * math.sin(t) - d * math.sin(k * t)) * scale
        return (cx + x * cr - y * sr, cy + x * sr + y * cr)

    return f


def rotate(p: Point, cx: float, cy: float, deg: float) -> Point:
    r = math.radians(deg)
    x, y = p[0] - cx, p[1] - cy
    return (
        cx + x * math.cos(r) - y * math.sin(r),
        cy + x * math.sin(r) + y * math.cos(r),
    )


# ---------------------------------------------------------------------------- strokes


@dataclass
class Ribbon:
    d: str
    fill: str
    opacity: float = 1.0
    cls: str = ""

    def svg(self, blend: str | None = None) -> str:
        """`blend` renders a `blend`-classed ribbon with that mix-blend-mode inline
        (for a gallery symbol); None keeps the class for the standalone stylesheet."""
        fill = "currentColor" if self.fill == INK else self.fill
        attrs = [f'd="{self.d}"', f'fill="{fill}"', 'fill-rule="evenodd"']
        if self.cls == "blend" and blend:
            attrs.insert(0, f'style="mix-blend-mode:{blend}"')
        elif self.cls:
            attrs.insert(0, f'class="{self.cls}"')
        if self.opacity < 1:
            attrs.append(f'opacity="{self.opacity:.2f}"')
        return f"<path {' '.join(attrs)}/>"


def stroke(
    curve: Curve,
    rng: random.Random,
    *,
    fill: str,
    width: float,
    samples: int = 96,
    wobble: float = 1.8,
    swell: float = 0.3,
    start: float = 0.0,
    overshoot: float | None = 0.06,
    drift: float = 1.6,
    sketch: bool = True,
    cls: str = "",
    opacity: float = 1.0,
) -> list[Ribbon]:
    """Draw `curve` as a hand-drawn ribbon.

    overshoot=None  — a seamless closed band (no visible join).
    overshoot=x     — one open stroke from `start` all the way round and x further, its
                      ends tapered: the loop is closed the way a hand closes it.
    sketch          — a second, thinner, fainter pass over part of the loop.
    """
    out: list[Ribbon] = []
    if overshoot is None:
        pts = trace(curve, 0.0, 1.0, samples, Wobble(rng, wobble))
        out.append(
            Ribbon(outline(pts, pen(rng, width, swell), True), fill, opacity, cls)
        )
    else:
        u1 = start + 1.0 + overshoot
        pts = trace(curve, start, u1, samples, Wobble(rng, wobble), drift)
        out.append(
            Ribbon(
                outline(pts, pen(rng, width, swell, taper=0.05), False),
                fill,
                opacity,
                cls,
            )
        )
    if sketch:
        a = start + rng.uniform(0.05, 0.5)
        span = rng.uniform(0.3, 0.55)
        pts = trace(
            curve, a, a + span, max(24, int(samples * span)), Wobble(rng, wobble * 1.4)
        )
        out.append(
            Ribbon(
                outline(pts, pen(rng, width * 0.5, 0.2, taper=0.12), False),
                fill,
                opacity * 0.45,
                cls,
            )
        )
    return out


def dot(
    cx: float, cy: float, r: float, rng: random.Random, *, fill: str, cls: str = ""
) -> Ribbon:
    pts = trace(circle(cx, cy, r * 0.55), 0.0, 1.0, 32, Wobble(rng, r * 0.08))
    return Ribbon(outline(pts, lambda _u: r * 0.9, True), fill, 1.0, cls)


