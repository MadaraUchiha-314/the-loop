        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {SIZE:.0f} {SIZE:.0f}" '
        f'color="{INK}" role="img" aria-labelledby="the-loop-logo-title the-loop-logo-desc">\n'
