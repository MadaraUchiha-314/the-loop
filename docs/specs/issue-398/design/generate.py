"""the-loop logo options (issue-398): five hand-drawn SVG marks from one generator.

Usage:

    python3 generate.py            write the five SVGs and the gallery next to this file
    python3 generate.py --check    verify the files on disk are exactly what this script
                                   makes, well-formed, self-contained and titled

Standard library only. Every mark is built from *ribbons*: a centreline sampled from a
parametric curve, pushed sideways by seeded low-frequency noise (the wobble of a hand),
then outlined with a width that swells and tapers (the pressure of a pen). The outline
is a closed, filled path — nothing depends on stroke rendering, filters or fonts, so the
files render the same in a browser, a README, a favicon and an image tool. Change a
parameter, re-run, and every file is regenerated byte-for-byte.
"""

