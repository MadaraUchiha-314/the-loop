"""the-loop logo options (issue-398): five brush-drawn SVG marks from one generator.

Usage:

    python3 generate.py            write the five SVGs and the gallery next to this file
    python3 generate.py --check    verify the files on disk are exactly what this script
                                   makes, well-formed, self-contained and titled

Standard library only. Every mark is one or more *strokes*: a centreline (a parametric
curve, or a spline through hand-placed points) outlined by a flat brush — thick across
the nib and thin along it, pressed harder mid-stroke, lifted in and out — and emitted as
one filled path. Nothing depends on stroke rendering, filters or fonts, so the files
render the same in a browser, a README, a favicon and an image tool. Change a parameter,
re-run, and every file is regenerated byte-for-byte.

Round 1 (git history) drew five loop *structures* with a wobbling, over-drawn hand; the
owner's review asked for character and less stress on the hand-drawn part. Round 2 keeps
the hand — a brush, held at an angle, lifted where it stops — and gives each mark a
personality instead of a diagram.
"""

